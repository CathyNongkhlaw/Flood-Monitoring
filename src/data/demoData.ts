function buildHistory(
  baseLevel: number,
  trend: number[],
  rain: number[],
  tempBase?: number,
  humidityBase?: number
): SensorReadingPoint[] {
  const labels = [
    '06:00',
    '08:00',
    '10:00',
    '12:00',
    '14:00',
    '16:00',
    '18:00',
    '20:00',
  ];
  return labels.map((label, i) => {
    const level = Number((baseLevel + trend[i]).toFixed(2));
    const prev = i === 0 ? level : Number((baseLevel + trend[i - 1]).toFixed(2));
    return {
      timestamp: `2026-11-20 ${label} IST`,
      label,
      waterLevelM: level,
      rainfallMmHr: rain[i],
      deltaM: Number((level - prev).toFixed(2)),
      temperatureC:
        tempBase !== undefined ? Number((tempBase + (i % 3) * 0.4).toFixed(1)) : undefined,
      humidityPct:
        humidityBase !== undefined ? Math.min(98, humidityBase + (i % 4)) : undefined,
    };
  });
}

